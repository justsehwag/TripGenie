// chat-dates-xp-fixes task 6.1: Properties 6-9 (plain chat text).
import { describe, it, expect } from "vitest";
import fc from "fast-check";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { parseChatText, stripMarkdown } from "@/lib/assistant/format";
import { ChatText } from "@/components/chat-text";

const RUNS = { numRuns: 150 };
const word = fc.stringMatching(/^[A-Za-z]{1,8}$/);

describe("Property 6: no ** markers in chat output", () => {
  it("no inline text contains '**' for any input", () => {
    fc.assert(
      fc.property(fc.oneof(fc.string(), fc.fullUnicodeString(), fc.array(fc.constantFrom("**", "a", " ", "\n", "*", "`", "_", "#", "- ", "1. ", "b"), { maxLength: 30 }).map((a) => a.join(""))), (input) => {
        for (const b of parseChatText(input)) {
          const parts = b.kind === "paragraph" ? b.inline : b.items.flat();
          for (const p of parts) expect(p.text).not.toContain("**");
        }
      }),
      RUNS,
    );
  });
  it("renders **text** as strong without asterisks", () => {
    const html = renderToStaticMarkup(createElement(ChatText, { text: "Visit **Fort Kochi** today" }));
    expect(html).toContain("<strong>Fort Kochi</strong>");
    expect(html).not.toContain("*");
  });
});

describe("Property 7: chat output carries no HTML", () => {
  // <br /> is generated by ChatText for in-paragraph "\n"; it is not HTML taken from the input.
  const ALLOWED = new Set(["p", "ol", "ul", "li", "strong", "br"]);
  it("only p/ol/ul/li/strong/br elements appear and input angle brackets are escaped", () => {
    fc.assert(
      fc.property(
        fc.oneof(
          fc.string(),
          fc.array(fc.constantFrom("<script>alert(1)</script>", "<b>", "</i>", "<img src=x>", "a", " ", "\n", "**", "- ", "1. ", "&"), { maxLength: 20 }).map((a) => a.join("")),
        ),
        (input) => {
          const html = renderToStaticMarkup(createElement(ChatText, { text: input }));
          const tags = [...html.matchAll(/<\/?([a-zA-Z][a-zA-Z0-9]*)/g)].map((m) => m[1].toLowerCase());
          for (const t of tags) expect(ALLOWED.has(t), `${t} in ${html}`).toBe(true);
          expect(html).not.toContain("<script");
        },
      ),
      RUNS,
    );
  });
  it("shows script text as plain characters and never uses dangerouslySetInnerHTML", () => {
    const html = renderToStaticMarkup(createElement(ChatText, { text: "<script>x</script>" }));
    expect(html).toContain("&lt;script&gt;");
    const src = readFileSync(join(__dirname, "..", "components", "chat-text.tsx"), "utf8");
    expect(src).not.toContain("dangerouslySetInnerHTML");
  });
});

describe("Property 8: formatting preserves words", () => {
  // Inputs are free of leading numbered prefixes ("1. "), because list numbers are
  // deliberately stripped by the parser. Words are letters only; they may be decorated
  // with markdown markers (**w**, *w*, `w`, _w_) and are separated by spaces or newlines.
  const decorated = fc.tuple(word, fc.constantFrom("", "**", "*", "`", "_")).map(([w, d]) => ({ w, text: `${d}${w}${d}` }));
  const sep = fc.constantFrom(" ", "\n", "\n\n");
  const words = (s: string) => (s.match(/[\p{L}\p{N}]+/gu) ?? []).sort();
  it("the alphanumeric words are unchanged", () => {
    fc.assert(
      fc.property(fc.array(fc.tuple(decorated, sep), { minLength: 1, maxLength: 15 }), (parts) => {
        const input = parts.map(([d, s], i) => d.text + (i < parts.length - 1 ? s : "")).join("");
        expect(words(stripMarkdown(input))).toEqual(words(input));
      }),
      RUNS,
    );
  });
});

describe("Property 9: lists are recognised", () => {
  const items = fc.array(word, { minLength: 1, maxLength: 10 });
  it("numbered lines give one ol with the same item count", () => {
    fc.assert(
      fc.property(items, (xs) => {
        const blocks = parseChatText(xs.map((x, i) => `${i + 1}. ${x}`).join("\n"));
        expect(blocks).toHaveLength(1);
        expect(blocks[0].kind).toBe("ol");
        if (blocks[0].kind === "ol") expect(blocks[0].items).toHaveLength(xs.length);
      }),
      RUNS,
    );
  });
  it("dashed lines give one ul with the same item count", () => {
    fc.assert(
      fc.property(items, (xs) => {
        const blocks = parseChatText(xs.map((x) => `- ${x}`).join("\n"));
        expect(blocks).toHaveLength(1);
        expect(blocks[0].kind).toBe("ul");
        if (blocks[0].kind === "ul") expect(blocks[0].items).toHaveLength(xs.length);
      }),
      RUNS,
    );
  });
  it("returns [] for empty input", () => {
    expect(parseChatText("")).toEqual([]);
  });
});
